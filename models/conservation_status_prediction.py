# Prepare the data for conservation status prediction
# Select relevant features (categorical and numerical)
X_conservation = df[['Height (cm)', 'Weight (kg)', 'Gestation Period (days)', 'Top Speed (km/h)', 'Offspring per Birth',
                       'Diet_Carnivore', 'Habitat_Oceans', 'Social Structure_Group-based']]

# Target variable (ensure it's binary or properly encoded)
