X_conservation_scaled = scaler_conservation.fit_transform(X_conservation)


# Split the data into training and testing sets
X_train_conservation, X_test_conservation, y_train_conservation, y_test_conservation = train_test_split(
    X_conservation_scaled, y_conservation, test_size=0.2, random_state=42
)

# Train a Logistic Regression model (you can use others, like RandomForestClassifier)
logistic_model = LogisticRegression(random_state=42)  # Use random_state for reproducibility
logistic_model.fit(X_train_conservation, y_train_conservation)

# Make predictions on the test set
y_pred_conservation = logistic_model.predict(X_test_conservation)

# Evaluate the conservation status model
accuracy_conservation = accuracy_score(y_test_conservation, y_pred_conservation)
